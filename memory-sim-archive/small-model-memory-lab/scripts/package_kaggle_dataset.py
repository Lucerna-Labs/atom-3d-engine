def copy_file(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)


def copy_tree_files(src_root, dst_root, patterns):
    for pattern in patterns:
        for src in src_root.rglob(pattern):
            if src.is_file():
                rel = src.relative_to(src_root)
                copy_file(src, dst_root / rel)


def copy_run_summary(lab_root, out_dir, run_name):
    src = lab_root / "runs" / run_name
    if not src.exists():
        return {"run": run_name, "copied": False, "reason": "missing"}

    dst = out_dir / "runs" / run_name
    copied = []

    for path in src.iterdir():
        if path.is_file() and path.suffix.lower() in {".json", ".csv", ".txt", ".md"}:
            copy_file(path, dst / path.name)
            copied.append(path.name)

    for name in ["summary.csv", "aggregate.json", "prefill.response.json", "primitive_prefix.txt"]:
        path = src / name
        if path.exists() and name not in copied:
            copy_file(path, dst / name)
            copied.append(name)

    for response in src.rglob("*.response.txt"):
        rel = response.relative_to(src)
        copy_file(response, dst / rel)
        copied.append(str(rel))

    return {"run": run_name, "copied": True, "files": copied}


